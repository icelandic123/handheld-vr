// Generates src/shadow/rest-hand.ts from IWER's relaxed left-hand pose (MIT, Meta Platforms).
// Run: node scripts/gen-rest-hand.mjs
import { writeFileSync } from 'node:fs';
import { relaxedHandPose } from '../node_modules/iwer/lib/device/configs/hand/relaxed.js';
const names = Object.keys(relaxedHandPose.jointTransforms);
const r = (x) => Math.round(x * 1e5) / 1e5;
const joints = names.map((n) => ({
  name: n,
  m: Array.from(relaxedHandPose.jointTransforms[n].offsetMatrix, r),
  radius: r(relaxedHandPose.jointTransforms[n].radius),
}));
const out = `// AUTO-GENERATED by scripts/gen-rest-hand.mjs — do not edit.
// Rest (relaxed) left-hand joint matrices, column-major, relative to the
// target-ray space. Derived from IWER's relaxed hand pose (MIT License,
// Copyright (c) Meta Platforms, Inc. and affiliates).
export const REST_JOINT_NAMES = ${JSON.stringify(names)} as const;
export const REST_JOINT_MATRICES: number[][] = ${JSON.stringify(joints.map((j) => j.m))};
export const REST_JOINT_RADII: number[] = ${JSON.stringify(joints.map((j) => j.radius))};
`;
writeFileSync(new URL('../src/shadow/rest-hand.ts', import.meta.url), out);
console.log('wrote', names.length, 'joints');
